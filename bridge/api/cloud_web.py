"""Adapt the live desktop's fixed assets to an account-Web computer namespace."""
import hashlib
import json
import re
import secrets

from bridge.api.assets import (STATIC, FONT_ROUTE, PDF_CMAP_ROUTE, PDF_FONT_ROUTE,
                               _HTML_URL, _CSS_URL, current_version, served_asset_bytes)
from bridge.api.html_preview import SHELL_PATH as HTML_SHELL
from bridge.api.mermaid_render import SHELL_PATH as MERMAID_SHELL


def is_resource(path):
    return (path in STATIC or path in (HTML_SHELL, MERMAID_SHELL)
            or any(route.fullmatch(path) for route in (FONT_ROUTE, PDF_CMAP_ROUTE, PDF_FONT_ROUTE)))


def adapt_response(server, path, body, headers, request):
    """Only trusted fixed HTML/CSS and the auth descriptor are transformed."""
    base, origin = request['base'], request['origin']
    if path == '/api/auth':
        value = json.loads(body)
        value.update(csrf=request['csrf'], connection={'mode': 'cloud'}, passwordless=True,
                     draftIdentity=request['account_id'] + ':' + base + ':' + value.get('draftIdentity', ''))
        value.pop('cookieName', None)
        value['listCacheIdentity'] = hashlib.sha256((request['account_id'] + ':' + base + ':' + value.get('listCacheIdentity', '')).encode()).hexdigest()
        body = json.dumps(value, ensure_ascii=False).encode()
    elif path == MERMAID_SHELL:
        # Opaque sandbox subresources cannot carry the Strict account cookie.
        # Inline only these two fixed desktop scripts under a fresh CSP nonce.
        nonce = secrets.token_urlsafe(24)
        for relative in ('vendor/mermaid/mermaid.min.js', 'mermaid-render-frame.js'):
            script = served_asset_bytes(server.web_dir, '/' + relative)
            if re.search(rb'</script', script, re.I):
                raise ValueError('unsafe fixed renderer script')
            pattern = rb'<script src="' + re.escape(relative.encode()) + rb'(?:\?[^"<>]*)?"></script>'
            replacement = b'<script nonce="' + nonce.encode() + b'">' + script + b'</script>'
            body, count = re.subn(pattern, lambda _: replacement, body)
            if count != 1:
                raise ValueError('missing fixed renderer script')
        headers['Content-Security-Policy'] = re.sub(r'script-src [^;]+', "script-src 'nonce-" + nonce + "'", headers['Content-Security-Policy'])
    elif path in STATIC:
        mime = STATIC[path][1]
        if path == '/manifest.webmanifest':
            value = json.loads(body)
            value['start_url'] = base + '/'
            value['scope'] = base + '/'
            value['id'] = base + '/'
            for icon in value.get('icons', []):
                if icon.get('src', '').startswith('/'):
                    icon['src'] = base + icon['src']
            body = json.dumps(value, ensure_ascii=False).encode()
        elif mime.startswith('text/html'):
            def reference(match):
                return match['prefix'] + base.encode() + match['url'] + match['suffix']
            body = _HTML_URL.sub(reference, body)
            if path == '/':
                version = current_version(server.web_dir, '/cloud-web.js')
                script = ('<script src="' + base + '/cloud-web.js?v=' + version + '" '
                          'data-base="' + base + '" data-account="' + request['account_id'] + '"></script>')
                body = body.replace(b'<head>', b'<head>' + script.encode(), 1)
        elif mime.startswith('text/css'):
            def css_reference(match):
                url = match['url']
                if not url.startswith(b'/') or url.startswith(b'//'):
                    return match[0]
                return b'url(' + match['quote'] + base.encode() + url + match['quote'] + b')'
            body = _CSS_URL.sub(css_reference, body)
    csp = headers.get('Content-Security-Policy', '')
    if csp:
        # The private loopback origin is generated by us, never supplied by the browser.
        local = request['local_origin']
        csp = csp.replace(local + HTML_SHELL, origin + base + HTML_SHELL)
        csp = csp.replace(local + MERMAID_SHELL, origin + base + MERMAID_SHELL)
        headers['Content-Security-Policy'] = csp.replace(local, origin)
    headers['Content-Length'] = str(len(body))
    if 'ETag' in headers:
        headers['ETag'] = '"' + hashlib.sha256(body).hexdigest()[:24] + '"'
    return body, headers

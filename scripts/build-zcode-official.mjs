// Build-only adapter: the shipped application needs neither this checkout nor npm.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.argv[2] || join(root, '.tmp/official-zcode-build'));
const tools = resolve(process.argv[3] || join(root, '.tmp/zcode-official-build-tools/node_modules'));
const revision = 'a9fe401eede6e6e5e01be9048679c206fe6f02d9';
if (execFileSync('git', ['rev-parse', 'HEAD'], { cwd: source, encoding: 'utf8' }).trim() !== revision)
  throw Error('The official source checkout does not match the audited revision');
const { build } = await import(pathToFileURL(join(tools, 'esbuild/lib/main.js')));
const output = join(root, 'desktop/features/zcode-official/vendor');
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: source,
  stdin: { contents: `
export { createAcknowledgedWebRemoteControlRelayProtocol } from './packages/client/src/webRemoteControlAcknowledgedRelayProtocol.ts';
export { ChannelClient, ChannelServer, ProxyChannel, Emitter } from './packages/rpc/src/index.ts';
export { ServiceChannels } from './packages/shared/src/channels.ts';
export { SessionDataLayer } from './packages/ui/src/v4/sessionDataLayer.ts';
export { createAgentConversationTransport } from './packages/ui/src/v4/agentConversationTransport.ts';
export { getV4ClientId } from './packages/ui/src/v4/commandFactory.ts';
export { ensureAgentV4ConnectionHandshake } from './packages/ui/src/v4/agentV4ConnectionHandshake.ts';
`, resolveDir: source, sourcefile: 'bridge-official-entry.ts', loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', target: 'node22',
  nodePaths: [tools], metafile: true, write: false, minify: true,
  legalComments: 'eof', define: { 'import.meta.env': '{"PROD":true}' },
  plugins: [{ name: 'official-workspace-packages', setup(api) {
    api.onResolve({ filter: /^@\// }, args => ({ path: join(source, 'packages/ui/src', args.path.slice(2).replace(/\.js$/, '.ts')) }));
    api.onResolve({ filter: /^@zcode\// }, async args => {
      const [, name, ...subpath] = args.path.split('/');
      const dir = join(source, 'packages', name);
      const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
      let target = pkg.exports?.[subpath.length ? './' + subpath.join('/') : '.'];
      if (target && typeof target === 'object') target = target.default;
      if (!target) throw Error('Unsupported official package export: ' + args.path);
      return { path: resolve(dir, target) };
    });
  } }],
});
const bytes = Buffer.from(`// ZCode official protocol and conversation layer, Apache-2.0.\n// Source: https://github.com/zai-org/ZCode/tree/${revision}\n// Generated by scripts/build-zcode-official.mjs; see NOTICE.md and LICENSE.ZCode.\n` + result.outputFiles[0].text);
await writeFile(join(output, 'zcode-official.mjs'), bytes);
await copyFile(join(source, 'LICENSE'), join(output, 'LICENSE.ZCode'));
await copyFile(join(tools, 'zod/LICENSE'), join(output, 'LICENSE.zod'));
await writeFile(join(output, 'manifest.json'), JSON.stringify({ repository: 'https://github.com/zai-org/ZCode', revision,
  sha256: createHash('sha256').update(bytes).digest('hex'),
  sourceFiles: Object.keys(result.metafile.inputs).filter(path => path.startsWith('packages/')).sort(),
  dependencies: { zod: JSON.parse(await readFile(join(tools, 'zod/package.json'), 'utf8')).version },
}, null, 2) + '\n');
console.log('Built official ZCode protocol bundle: ' + bytes.length + ' bytes');
